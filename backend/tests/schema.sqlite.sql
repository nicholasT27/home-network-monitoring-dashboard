CREATE TABLE devices (mac TEXT PRIMARY KEY, ip TEXT NOT NULL, hostname TEXT, vendor TEXT, label TEXT,
  status TEXT NOT NULL DEFAULT 'unknown', suspicious INTEGER NOT NULL DEFAULT 0, suspicious_reason TEXT,
  online INTEGER NOT NULL DEFAULT 0, first_seen TEXT NOT NULL, last_seen TEXT NOT NULL);
CREATE TABLE connection_history (id INTEGER PRIMARY KEY AUTOINCREMENT, mac TEXT NOT NULL, ip TEXT, hostname TEXT,
  event TEXT NOT NULL, event_time TEXT NOT NULL);
CREATE TABLE alerts (id INTEGER PRIMARY KEY AUTOINCREMENT, mac TEXT NOT NULL, ip TEXT, hostname TEXT, type TEXT NOT NULL,
  message TEXT NOT NULL, email_sent INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, acknowledged_at TEXT);
CREATE TABLE scans (id INTEGER PRIMARY KEY AUTOINCREMENT, started_at TEXT NOT NULL, duration_ms INTEGER NOT NULL,
  devices_found INTEGER NOT NULL, new_unknown INTEGER NOT NULL DEFAULT 0, source TEXT NOT NULL DEFAULT 'manual');
CREATE TABLE settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);
